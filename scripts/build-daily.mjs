// Builds prototype/daily.js (거래일 단위 종가) for the story chapters.
// Usage: node scripts/build-daily.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SYMS = ["AAPL", "AMZN", "ZM", "NFLX", "AAL", "CCL", "XOM", "SPY"];
const FROM = "2019-07-01";
const read = (sym) => new Map(readFileSync(join(root, "data/raw", `${sym}.csv`), "utf8").trim().split("\n").slice(1).map((l) => l.split(",")).map(([d, v]) => [d, Number(v)]));
const series = Object.fromEntries([...SYMS, "VIX"].map((s) => [s, read(s)]));
const dates = [...series.SPY.keys()].filter((d) => d >= FROM && SYMS.every((s) => series[s].has(d))).sort();
const round = (v, n) => Math.round(v * 10 ** n) / 10 ** n;
const out = {
  source: "실제 일별 수정 종가(분할·배당 반영), data/SOURCES.md 참고",
  usdKrw: 1200,
  dates,
  prices: Object.fromEntries(SYMS.map((s) => [s, dates.map((d) => round(series[s].get(d), 4))])),
  vix: dates.map((d) => series.VIX.get(d) ?? null),
};
writeFileSync(join(root, "prototype/daily.js"), "// Generated by scripts/build-daily.mjs — do not edit by hand.\nwindow.RAUM_DAILY = " + JSON.stringify(out) + ";\n");
console.log(`days: ${dates.length}, ${dates[0]} → ${dates.at(-1)}`);
