// Gemini에서 받은 2x2 그림판(네 장면을 흰 줄로 나눈 그림)을 장면 네 장으로 잘라 prototype/img/kid/<id>.webp 로 저장합니다.
// Usage: node scripts/split-kid-grid.mjs <grid.png> <왼쪽위 id> <오른쪽위 id> [왼쪽아래 id] [오른쪽아래 id]
//   - id 자리에 - 를 쓰면 그 칸은 건너뜀
//   - 흰 줄(가운데 근처의 거의 흰 세로/가로 줄)을 찾아서 자르고, 칸마다 1200x900(4:3)으로 맞춤
//   - 원본 그림판은 .cache/kid-art/grid-<첫 id>.png 로 복사해 둠
//   - 끝나면 prototype/img/kid/list.js 목록에 새 id를 더함
import { spawn } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const [src, ...ids] = process.argv.slice(2);
if (!src || !ids.length) throw new Error("사용법: node scripts/split-kid-grid.mjs <grid.png> <id1> <id2> [id3] [id4]");
const CACHE = join(root, ".cache/kid-art"), OUT = join(root, "prototype/img/kid");
mkdirSync(CACHE, { recursive: true });
copyFileSync(src, join(CACHE, `grid-${ids.find((x) => x !== "-")}.png`));

const edge = [process.env["ProgramFiles(x86)"], process.env.ProgramFiles, "C:/Program Files (x86)", "C:/Program Files"].filter(Boolean)
  .map((p) => join(p, "Microsoft", "Edge", "Application", "msedge.exe")).find((p) => existsSync(p));
const port = 9337;
const proc = spawn(edge, ["--headless=new", `--remote-debugging-port=${port}`, `--user-data-dir=${mkdtempSync(join(tmpdir(), "raum-grid-"))}`, "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let targets = [];
for (let i = 0; i < 40 && !targets.length; i++) { try { targets = (await (await fetch(`http://127.0.0.1:${port}/json`)).json()).filter((t) => t.type === "page"); } catch {} await sleep(250); }
const ws = new WebSocket(targets[0].webSocketDebuggerUrl);
await new Promise((r) => ws.addEventListener("open", r));
let mid = 0; const pend = new Map();
ws.addEventListener("message", (e) => { const m = JSON.parse(e.data); if (m.id) pend.get(m.id)?.(m); });
const send = (method, params = {}) => new Promise((r) => { const i = ++mid; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });

const b64 = readFileSync(src).toString("base64");
const r = await send("Runtime.evaluate", { awaitPromise: true, returnByValue: true, expression: `new Promise((res) => {
  const im = new Image();
  im.onload = () => {
    const W = im.width, H = im.height, c = document.createElement("canvas"); c.width = W; c.height = H;
    const g = c.getContext("2d", { willReadFrequently: true }); g.drawImage(im, 0, 0);
    const px = g.getImageData(0, 0, W, H).data;
    const white = (x, y) => { const i = (y * W + x) * 4; return px[i] > 232 && px[i + 1] > 232 && px[i + 2] > 232; };
    // 가운데 40~60% 구간에서 '거의 다 흰' 줄을 찾음
    const gap = (n, len, at) => { let best = null, run = null;
      for (let k = Math.floor(n * 0.4); k < n * 0.6; k++) {
        let w = 0, t = 0; for (let j = Math.floor(len * 0.05); j < len * 0.95; j += 3) { t++; if (at(k, j)) w++; }
        if (w / t > 0.85) { run ||= [k, k]; run[1] = k; } else if (run) { if (!best || run[1] - run[0] > best[1] - best[0]) best = run; run = null; }
      }
      if (run && (!best || run[1] - run[0] > best[1] - best[0])) best = run;
      return best || [Math.floor(n / 2), Math.floor(n / 2)]; };
    const gx = gap(W, H, (x, y) => white(x, y)), gy = gap(H, W, (y, x) => white(x, y));
    const cells = [[0, 0, gx[0], gy[0]], [gx[1] + 1, 0, W, gy[0]], [0, gy[1] + 1, gx[0], H], [gx[1] + 1, gy[1] + 1, W, H]];
    const out = cells.map(([x0, y0, x1, y1]) => {
      const ins = Math.round(Math.min(x1 - x0, y1 - y0) * 0.012); x0 += ins; y0 += ins; x1 -= ins; y1 -= ins;
      const o = document.createElement("canvas"); o.width = 1200; o.height = 900;
      const w = x1 - x0, h = y1 - y0, s = Math.max(1200 / w, 900 / h), cw = 1200 / s, ch = 900 / s;
      o.getContext("2d").drawImage(c, x0 + (w - cw) / 2, y0 + (h - ch) / 2, cw, ch, 0, 0, 1200, 900);
      return o.toDataURL("image/webp", 0.85).split(",")[1];
    });
    res({ W, H, gx, gy, out });
  };
  im.src = "data:image/png;base64,${b64}";
})` });
const v = r.result.result.value;
console.log(`그림판 ${v.W}x${v.H}, 세로 흰 줄 ${v.gx.join("-")}, 가로 흰 줄 ${v.gy.join("-")}`);
const done = [];
ids.forEach((id, i) => {
  if (id === "-" || !v.out[i]) return;
  const buf = Buffer.from(v.out[i], "base64");
  writeFileSync(join(OUT, `${id}.webp`), buf);
  done.push(id);
  console.log(`${id}.webp ${(buf.length / 1024).toFixed(0)}KB`);
});
ws.close(); proc.kill();

// 그림 목록에 더하기 (이름 순서로)
const listPath = join(OUT, "list.js");
const old = existsSync(listPath) ? JSON.parse(readFileSync(listPath, "utf8").match(/=\s*(\[[\s\S]*?\])/)[1]) : [];
const all = [...new Set([...old, ...done])].sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
writeFileSync(listPath, `// Generated by scripts/gen-kid-images.mjs / split-kid-grid.mjs — do not edit by hand.\nwindow.RAUM_KID_IMGS = ${JSON.stringify(all)};\n`);
console.log(`목록: ${all.length}장`);
process.exit(0);
