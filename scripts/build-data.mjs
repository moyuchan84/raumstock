// Builds prototype/data.js from the real daily CSVs in data/raw.
// One game turn = one trading week. Turn 0 = the first week of 2020.
// Usage: node scripts/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = (name) =>
  readFileSync(join(root, "data/raw", name), "utf8")
    .trim()
    .split("\n")
    .slice(1)
    .map((l) => l.split(","));

const daily = (sym) => raw(`${sym}.csv`).map(([d, v]) => [d, Number(v)]);

const ASSETS = ["ZM", "AMZN", "AAL", "CCL", "XOM", "AAPL", "NFLX", "SPY", "QQQ", "EWY", "XLE", "TLT", "SHY", "GLD", "USO"];
const PRE_WEEKS = 26; // weeks of history shown before the game starts
const START = "2020-01-01";
const USD_KRW = 1200; // fixed rate used to show prices in 원 (simplification)

// ISO-like week key: the Monday of that week.
function weekKey(date) {
  const d = new Date(date + "T00:00:00Z");
  const dow = (d.getUTCDay() + 6) % 7; // Mon=0
  d.setUTCDate(d.getUTCDate() - dow);
  return d.toISOString().slice(0, 10);
}

// Turn dates = last SPY trading day of each week.
const spy = daily("SPY");
const lastDayOfWeek = new Map();
for (const [d] of spy) lastDayOfWeek.set(weekKey(d), d);
const allWeekEnds = [...lastDayOfWeek.values()].sort();
const firstGame = allWeekEnds.findIndex((d) => d >= START);
const weekEnds = allWeekEnds.slice(firstGame - PRE_WEEKS);

// value on or before a date
function asOf(series, date) {
  let v = null;
  for (const [d, x] of series) {
    if (d > date) break;
    v = x;
  }
  return v;
}
const r2 = (x) => Math.round(x * 100) / 100;

const prices = {};
for (const sym of ASSETS) {
  const s = daily(sym);
  prices[sym] = weekEnds.map((d) => r2(asOf(s, d)));
}

// Indicators
const wti = daily("WTI");
const vix = daily("VIX");
const tenY = new Map(raw("US10Y_monthly.csv").map(([m, v]) => [m, Number(v)]));
// Fed funds target, upper bound (real FOMC decisions)
const FED = [
  ["2019-01-01", 2.5],
  ["2019-08-01", 2.25],
  ["2019-09-19", 2.0],
  ["2019-10-31", 1.75],
  ["2020-03-03", 1.25],
  ["2020-03-15", 0.25],
];
const fedAt = (d) => FED.filter(([x]) => x <= d).at(-1)[1];

const weekStartOf = (i) => (i === 0 ? "0000" : weekEnds[i - 1]);
const indicators = weekEnds.map((d, i) => {
  const inWeek = wti.filter(([x]) => x > weekStartOf(i) && x <= d).map(([, v]) => v);
  return {
    fed: fedAt(d),
    y10: tenY.get(d.slice(0, 7)),
    oil: r2(asOf(wti, d)),
    oilMin: inWeek.length ? r2(Math.min(...inWeek)) : r2(asOf(wti, d)),
    vix: r2(asOf(vix, d)),
  };
});

const out = {
  source: "실제 2019-2020 일별 종가 (data/SOURCES.md 참고), 주 마지막 거래일 기준",
  usdKrw: USD_KRW,
  preWeeks: PRE_WEEKS,
  dates: weekEnds,
  prices,
  indicators,
};

writeFileSync(
  join(root, "prototype/data.js"),
  "// Generated by scripts/build-data.mjs — do not edit by hand.\nwindow.RAUM_DATA = " + JSON.stringify(out) + ";\n"
);
console.log(`weeks: ${weekEnds.length} (game turns: ${weekEnds.length - PRE_WEEKS}), first turn ${weekEnds[PRE_WEEKS]}, last ${weekEnds.at(-1)}`);
