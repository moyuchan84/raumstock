// 역사 스테이지용 실제 일별 수정 종가를 받아 저장합니다.
//  - 원본: data/raw/stages/<id>.csv  (Date, 종목별 수정 종가)
//  - 게임용: prototype/stages-real.js (window.RAUM_HIST)
// 출처: Yahoo Finance chart API (분할·배당 반영 adjclose). 프로토타입용이며 출시 전 라이선스 데이터로 교체해야 함.
// Usage: node scripts/fetch-stages.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// from~to: 플레이 구간, pre: 시작 전에 보여 줄 과거(달력 일수)
export const STAGES = [
  { id: "h1987", from: "1987-08-03", to: "1987-12-31", syms: ["^GSPC", "IBM", "KO", "GE", "XOM"] },
  { id: "h2000", from: "2000-01-03", to: "2000-06-30", syms: ["MSFT", "CSCO", "INTC", "AMZN", "KO", "QQQ", "SPY"] },
  { id: "h2008", from: "2008-09-02", to: "2008-12-31", syms: ["BAC", "GS", "AIG", "GE", "WMT", "GLD", "SPY"] },
  { id: "h2009", from: "2009-01-02", to: "2009-06-30", syms: ["BAC", "GS", "AAPL", "WMT", "GLD", "SPY"] },
  { id: "h2011", from: "2011-07-01", to: "2011-10-31", syms: ["AAPL", "BAC", "JNJ", "GLD", "TLT", "SPY"] },
  { id: "h2018", from: "2018-10-01", to: "2019-01-31", syms: ["AAPL", "NVDA", "AMZN", "PG", "JNJ", "SPY"] },
  { id: "h2021", from: "2021-01-04", to: "2021-03-31", syms: ["GME", "AMC", "TSLA", "AAPL", "SPY"] },
  { id: "h2022", from: "2022-01-03", to: "2022-06-30", syms: ["META", "NFLX", "AMZN", "XOM", "TLT", "GLD", "SPY"] },
  { id: "h2023", from: "2023-01-03", to: "2023-06-30", syms: ["NVDA", "MSFT", "JPM", "KRE", "GLD", "SPY"] },
  { id: "k2021", from: "2020-11-02", to: "2021-03-31", syms: ["005930.KS", "000660.KS", "035420.KS", "035720.KS", "069500.KS"] },
];
const PRE_DAYS = 50;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const ts = (d) => Math.floor(new Date(d + "T00:00:00Z") / 1000);
const addDays = (d, n) => new Date(Date.parse(d + "T00:00:00Z") + n * 864e5).toISOString().slice(0, 10);

async function fetchSym(sym, from, to) {
  const url = `https://query1.finance.yahoo.com/v8/finance/chart/${encodeURIComponent(sym)}?period1=${ts(from)}&period2=${ts(addDays(to, 2))}&interval=1d&events=div,split`;
  for (let tryN = 0; tryN < 3; tryN++) {
    const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0 (raumstock-edu-prototype)" } });
    if (res.ok) {
      const r = (await res.json()).chart.result?.[0];
      if (!r?.timestamp) throw new Error(`${sym}: 데이터 없음`);
      const tz = r.meta.gmtoffset || 0;
      const adj = r.indicators.adjclose?.[0]?.adjclose || r.indicators.quote[0].close;
      const out = new Map();
      r.timestamp.forEach((t, i) => { if (adj[i] != null) out.set(new Date((t + tz) * 1000).toISOString().slice(0, 10), adj[i]); });
      return { map: out, currency: r.meta.currency };
    }
    await sleep(1500 * (tryN + 1));
  }
  throw new Error(`${sym}: 요청 실패`);
}

const hist = {};
mkdirSync(join(root, "data/raw/stages"), { recursive: true });
for (const s of STAGES) {
  const start = addDays(s.from, -PRE_DAYS);
  const got = {};
  let currency = null;
  for (const sym of s.syms) {
    const { map, currency: c } = await fetchSym(sym, start, s.to);
    got[sym] = map;
    currency ||= c;
    await sleep(400);
  }
  const dates = [...got[s.syms[0]].keys()].filter((d) => d <= s.to && s.syms.every((x) => got[x].has(d))).sort();
  const startIdx = dates.findIndex((d) => d >= s.from);
  const dec = (v) => Math.round(v * 10000) / 10000;
  hist[s.id] = { dates, start: startIdx, currency, prices: Object.fromEntries(s.syms.map((x) => [x, dates.map((d) => dec(got[x].get(d)))])) };
  const csv = ["Date," + s.syms.join(","), ...dates.map((d) => [d, ...s.syms.map((x) => dec(got[x].get(d)))].join(","))].join("\n");
  writeFileSync(join(root, `data/raw/stages/${s.id}.csv`), csv + "\n");
  console.log(`${s.id}: ${dates.length}일 (플레이 ${dates.length - startIdx}일) ${currency}`);
}
writeFileSync(join(root, "prototype/stages-real.js"), "// Generated by scripts/fetch-stages.mjs — do not edit by hand. 실제 일별 수정 종가 (Yahoo Finance)\nwindow.RAUM_HIST = " + JSON.stringify(hist) + ";\n");
