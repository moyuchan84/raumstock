// '긴 기다림' 체험용 10년 실제 수정 종가를 받아 저장합니다.
//  - 원본: data/raw/long/<id>.csv  (Date, Close = 분할·배당 반영 수정 종가, 일별)
//  - 게임용: prototype/long-real.js (window.RAUM_LONG): 첫 거래일 값 + 달마다 마지막 값, 해마다 가장 낮았던 하루 값
// 출처: Yahoo Finance chart API. 프로토타입용이며 출시 전 라이선스 데이터로 교체해야 함.
// Usage: node scripts/fetch-long.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const STORIES = [
  { id: "spy2007", sym: "SPY", from: 2007, to: 2016 },
  { id: "spy2000", sym: "SPY", from: 2000, to: 2009 },
  { id: "aig2007", sym: "AIG", from: 2007, to: 2016 },
  { id: "aapl2007", sym: "AAPL", from: 2007, to: 2016 },
];
const ts = (d) => Math.floor(Date.parse(d + "T00:00:00Z") / 1000);
const dec = (v) => Math.round(v * 10000) / 10000;

async function daily(sym, from, to) {
  const url = `https://query1.finance.yahoo.com/v8/finance/chart/${sym}?period1=${ts(`${from}-01-01`)}&period2=${ts(`${to + 1}-01-02`)}&interval=1d&events=div,split`;
  const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0 (raumstock-edu-prototype)" } });
  if (!res.ok) throw new Error(`${sym}: HTTP ${res.status}`);
  const r = (await res.json()).chart.result?.[0];
  const adj = r?.indicators.adjclose?.[0]?.adjclose;
  if (!adj) throw new Error(`${sym}: 수정 종가 없음`);
  const tz = r.meta.gmtoffset || 0;
  return r.timestamp
    .map((t, i) => [new Date((t + tz) * 1000).toISOString().slice(0, 10), adj[i]])
    .filter(([d, v]) => v != null && d >= `${from}-01-01` && d <= `${to}-12-31`);
}

const out = {};
mkdirSync(join(root, "data/raw/long"), { recursive: true });
for (const s of STORIES) {
  const rows = await daily(s.sym, s.from, s.to);
  writeFileSync(join(root, `data/raw/long/${s.id}.csv`), ["Date,Close", ...rows.map(([d, v]) => `${d},${dec(v)}`)].join("\n") + "\n");
  const ends = new Map(), lows = new Map();
  for (const [d, v] of rows) {
    ends.set(d.slice(0, 7), [d, v]);
    const y = d.slice(0, 4);
    if (!lows.has(y) || v < lows.get(y)) lows.set(y, v);
  }
  const months = [rows[0], ...ends.values()];
  if (months.length !== (s.to - s.from + 1) * 12 + 1) throw new Error(`${s.id}: 달 수가 맞지 않음 (${months.length})`);
  out[s.id] = { sym: s.sym, from: s.from, to: s.to, dates: months.map(([d]) => d), prices: months.map(([, v]) => dec(v)), lows: [...lows.values()].map(dec) };
  console.log(`${s.id}: ${rows.length}일 ${rows[0][0]} ~ ${rows.at(-1)[0]}`);
  await new Promise((r) => setTimeout(r, 400));
}
writeFileSync(join(root, "prototype/long-real.js"), "// Generated by scripts/fetch-long.mjs — do not edit by hand. 실제 수정 종가 (Yahoo Finance)\nwindow.RAUM_LONG = " + JSON.stringify(out) + ";\n");
